const path = require('node:path');
const fs = require('node:fs');
const { spawnSync } = require('node:child_process');
const assert = require('node:assert/strict');
const { ROOT, launch, attach, ensureSamples } = require('./cdp');

ensureSamples();
const img = path.join(ROOT, 'samples', 'quire-diagram.png');
const pdf = path.join(ROOT, 'samples', 'quire-sample.pdf');
const output = path.join(ROOT, 'test', 'out', 'image-edit-test.webp');

(async () => {
  const exeFlag = process.argv.indexOf('--exe');
  const binary = exeFlag < 0 ? undefined : path.resolve(process.argv[exeFlag + 1]);
  const { child, log } = launch({ port: 9257, args: [img], ...(binary ? { binary, app: null } : {}) });
  let browser;
  try {
    const connection = await attach(9257); browser = connection.browser;
    const page = connection.page;
    page.on('dialog', (dialog) => dialog.accept());
    await page.waitForFunction(() => document.body.classList.contains('image-mode'));
    await page.screenshot({ path: path.join(ROOT, 'test', 'out', 'image-workspace.png') });
    const dimensions = () => page.evaluate(() => [window.__quire.imageEditor.canvas.width, window.__quire.imageEditor.canvas.height]);
    const [width, height] = await dimensions();
    assert(width > 0 && height > 0);
    const overlay = await page.$eval('.image-overlay', (el) => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height }; });
    await page.select('#crop-ratio', '1');
    await page.mouse.move(overlay.x + overlay.w * 0.1, overlay.y + overlay.h * 0.1);
    await page.mouse.down();
    await page.mouse.move(overlay.x + overlay.w * 0.45, overlay.y + overlay.h * 0.7, { steps: 6 });
    await page.mouse.up();
    let selected = await page.evaluate(() => window.__quire.imageEditor.selection);
    assert(selected && Math.abs(selected.w - selected.h) <= 1, 'drag selects a square crop');
    assert.equal(await page.$eval('#image-crop', (el) => el.disabled), false);
    await page.screenshot({ path: path.join(ROOT, 'test', 'out', 'image-crop.png') });
    const center = await page.$eval('.crop-box', (el) => { const r = el.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; });
    await page.mouse.move(center.x, center.y); await page.mouse.down(); await page.mouse.move(center.x + 12, center.y + 8, { steps: 4 }); await page.mouse.up();
    const moved = await page.evaluate(() => window.__quire.imageEditor.selection);
    assert(moved.x > selected.x && moved.y > selected.y, 'drag moves a crop selection');
    const corner = await page.$eval('.crop-box [data-handle="se"]', (el) => { const r = el.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; });
    await page.mouse.move(corner.x, corner.y); await page.mouse.down(); await page.mouse.move(corner.x - 15, corner.y - 15, { steps: 4 }); await page.mouse.up();
    selected = await page.evaluate(() => window.__quire.imageEditor.selection);
    assert(selected.w < moved.w && Math.abs(selected.w - selected.h) <= 1, 'corner resizes the crop at its chosen ratio');
    await page.click('#image-crop');
    assert.deepEqual(await dimensions(), [selected.w, selected.h], 'crop button uses drawn bounds');
    await page.click('#image-undo');
    await page.waitForFunction((w) => window.__quire.imageEditor.canvas.width === w, {}, width);
    await page.click('[data-image-mode="resize"]');
    await page.$eval('#image-width', (el) => { el.value = 160; el.dispatchEvent(new Event('input', { bubbles: true })); });
    assert.equal(await page.$eval('#image-height', (el) => +el.value), Math.round(height * 160 / width), 'resize preserves aspect ratio');
    await page.click('[data-resize="0.5"]');
    await page.click('#image-resize');
    assert.deepEqual(await dimensions(), [Math.round(width / 2), Math.round(height / 2)]);
    await page.click('#image-undo');
    await page.waitForFunction((w) => window.__quire.imageEditor.canvas.width === w, {}, width);
    await page.click('[data-image-mode="adjust"]');
    const pixel = () => page.evaluate(() => Array.from(window.__quire.imageEditor.ctx.getImageData(10, 10, 1, 1).data));
    const originalPixel = await pixel();
    await page.$eval('#image-brightness', (el) => { el.value = 50; el.dispatchEvent(new Event('input', { bubbles: true })); });
    assert.match(await page.$eval('.image-canvas', (el) => el.style.filter), /brightness\(50%\)/);
    assert.deepEqual(await pixel(), originalPixel, 'preview does not modify pixels before apply');
    await page.click('#image-apply');
    assert.notDeepEqual(await pixel(), originalPixel, 'applying adjustment changes pixels');
    await page.click('#image-undo');
    await page.waitForFunction((p) => Array.from(window.__quire.imageEditor.ctx.getImageData(10, 10, 1, 1).data).join() === p.join(), {}, originalPixel);
    await page.click('[data-image-mode="draw"]');
    const beforeDraw = await page.evaluate(() => window.__quire.imageEditor.canvas.toDataURL());
    await page.mouse.move(overlay.x + 20, overlay.y + 20); await page.mouse.down(); await page.mouse.move(overlay.x + 100, overlay.y + 70, { steps: 5 }); await page.mouse.up();
    assert.notEqual(await page.evaluate(() => window.__quire.imageEditor.canvas.toDataURL()), beforeDraw, 'drawing changes the image');
    await page.click('#image-undo');
    await page.waitForFunction((before) => window.__quire.imageEditor.canvas.toDataURL() === before, {}, beforeDraw);
    await page.click('[data-image-mode="text"]');
    await page.type('#image-text', 'Hello');
    await page.mouse.click(overlay.x + 30, overlay.y + 30);
    assert.notEqual(await page.evaluate(() => window.__quire.imageEditor.canvas.toDataURL()), beforeDraw, 'click places text');
    await page.click('#image-undo');
    await page.waitForFunction((before) => window.__quire.imageEditor.canvas.toDataURL() === before, {}, beforeDraw);
    await page.click('#image-rotate-right');
    assert.deepEqual(await dimensions(), [height, width]);
    await page.click('#image-undo');
    await page.waitForFunction((w) => window.__quire.imageEditor.canvas.width === w, {}, width);
    await page.click('#image-redo');
    await page.waitForFunction((h) => window.__quire.imageEditor.canvas.width === h, {}, height);
    await page.evaluate(() => window.__quire.imageEditor.crop(0, 0, 40, 30));
    assert.deepEqual(await dimensions(), [40, 30]);
    await page.evaluate(() => window.__quire.imageEditor.resize(80, 60));
    await page.evaluate((file) => window.__quire.openPath(file), pdf);
    await page.click('.doc-tab:first-child');
    await page.waitForFunction(() => document.body.classList.contains('image-mode'));
    assert.deepEqual(await dimensions(), [80, 60], 'image edits survive tab switching');
    const saved = await page.evaluate((file) => window.__quire.exportImage(file), output);
    assert.equal(saved, output);
    assert.equal(fs.readFileSync(output).subarray(8, 12).toString(), 'WEBP');
    await page.click('[data-image-mode="adjust"]');
    await page.$eval('#image-brightness', (el) => { el.value = 50; el.dispatchEvent(new Event('input', { bubbles: true })); });
    const previewOutput = path.join(ROOT, 'test', 'out', 'image-preview-test.png');
    await page.evaluate((file) => window.__quire.openPath(file), pdf);
    await page.click('.doc-tab:first-child');
    await page.waitForFunction(() => document.body.classList.contains('image-mode'));
    assert.equal(await page.$eval('#image-brightness', (el) => +el.value), 50, 'preview survives tab switching');
    const previewPixels = await page.evaluate(async () => {
      const editor = window.__quire.imageEditor;
      const raw = Array.from(editor.ctx.getImageData(1, 1, 1, 1).data);
      const encoded = await editor.encode('image/png');
      const bitmap = await createImageBitmap(new Blob([encoded], { type: 'image/png' }));
      const canvas = document.createElement('canvas'); canvas.width = bitmap.width; canvas.height = bitmap.height;
      const ctx = canvas.getContext('2d'); ctx.drawImage(bitmap, 0, 0); bitmap.close();
      return { raw, exported: Array.from(ctx.getImageData(1, 1, 1, 1).data) };
    });
    assert(previewPixels.exported[0] < previewPixels.raw[0], 'export includes live preview');
    await page.click('#image-copy');
    await page.waitForFunction(() => Array.from(document.querySelectorAll('.toast')).some((el) => el.textContent === 'Image copied to clipboard'));
    assert.equal(await page.evaluate(() => window.__quire.state.edited), true, 'copying does not mark unexported edits as saved');
    if (process.platform === 'win32') {
      const read = spawnSync('powershell', ['-NoProfile', '-STA', '-Command', 'Add-Type -AssemblyName System.Windows.Forms; $image = [System.Windows.Forms.Clipboard]::GetImage(); if ($null -eq $image) { exit 1 }; "$($image.Width),$($image.Height),$($image.GetPixel(1,1).R)"'], { encoding: 'utf8' });
      assert.equal(read.status, 0, read.stderr);
      const [copiedWidth, copiedHeight, red] = read.stdout.trim().split(',').map(Number);
      assert.deepEqual([copiedWidth, copiedHeight], [80, 60], 'clipboard contains the edited image');
      assert(Math.abs(red - previewPixels.exported[0]) <= 1, 'clipboard includes the visible adjustment preview');
    }
    assert.equal(await page.evaluate((file) => window.__quire.exportImage(file), previewOutput), previewOutput);
    console.log('image: selection crop, resize lock, adjustments, drawing, text, undo, tabs and export: ok');
  } catch (err) { console.error(err, log.join('')); process.exitCode = 1; }
  finally { browser?.disconnect(); child.kill(); }
})();
